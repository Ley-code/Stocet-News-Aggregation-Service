# Categories that count as "market/financial" on their own. A story that only matches
# generic categories (Politics, Energy & Infrastructure, Agriculture) must also mention Ethiopia.
CORE_CATEGORIES = {
    "Treasury Bills",
    "Capital Markets",
    "Macroeconomics",
    "Banking",
    "Insurance",
    "Business & Trade",
}


def get_all_keywords() -> List[str]:
    """Get all keywords from all categories."""
    keywords = []
    for category_keywords in FINANCIAL_TAXONOMY.values():
        keywords.extend(category_keywords)
    return keywords


def get_keywords_by_category(category: str) -> List[str]:
    """Get keywords for a specific category."""
    return FINANCIAL_TAXONOMY.get(category, [])
